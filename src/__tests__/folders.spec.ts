import { flushPromises, mount } from '@vue/test-utils'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { createPinia, setActivePinia } from 'pinia'
import { describe, expect, it } from 'vitest'
import type { Component } from 'vue'

import { appTypes } from '@/apps'
import { faceTypes } from '@/faces'
import { useEntitiesStore } from '@/stores/entities'
import { themeTypes } from '@/themes'

// Every app type, face and theme folder: a description and a preview.png, which
// make the docs gallery (`npm run gallery` writes docs/gallery.md).
const GALLERY = join(process.cwd(), 'docs/gallery.md')
const folders = [
  ...appTypes.map((t) => ({ kind: 'apps', id: t.type, description: t.description })),
  ...faceTypes.map((f) => ({ kind: 'faces', id: f.id, description: f.description })),
  ...themeTypes.map((t) => ({ kind: 'themes', id: t.id, description: t.description })),
]

const TITLES = { apps: 'App types', faces: 'Faces', themes: 'Themes' }
const gallery = [
  '# Gallery',
  '',
  "Every app type, face and theme in `src/`, from each folder's `description` and `preview.png`.",
  'Generated by `npm run gallery`. To add your own, see [CONTRIBUTING.md](../CONTRIBUTING.md).',
  ...Object.entries(TITLES).flatMap(([kind, title]) => [
    '',
    `## ${title}`,
    '',
    '| Name | Preview | What it is |',
    '| --- | --- | --- |',
    ...folders
      .filter((folder) => folder.kind === kind)
      .map(
        ({ id, description }) =>
          `| \`${id}\` | <img src="../src/${kind}/${id}/preview.png" alt="${id}" width="240"> | ${description} |`,
      ),
  ]),
  '',
].join('\n')

describe('folders', () => {
  it.each(folders.map((folder) => [`${folder.kind}/${folder.id}`, folder] as const))(
    '%s has a description and a preview.png',
    (_, { kind, id, description }) => {
      expect(description.length).toBeGreaterThan(10)
      expect(existsSync(join(process.cwd(), 'src', kind, id, 'preview.png'))).toBe(true)
    },
  )

  it('docs/gallery.md shows them all (run `npm run gallery` after changing one)', () => {
    if (process.env.UPDATE_GALLERY) writeFileSync(GALLERY, gallery)
    expect(readFileSync(GALLERY, 'utf8')).toBe(gallery)
  })
})

describe('templates (npm run new) work as they are', () => {
  const templates = import.meta.glob<{ default: Record<string, unknown> }>(
    '../../templates/*/index.ts',
    { eager: true },
  )
  const load = async (loader: unknown) =>
    (await (loader as () => Promise<{ default: Component }>)()).default

  it('app: its widget and its screen render', async () => {
    setActivePinia(createPinia())
    const definition = templates['../../templates/app/index.ts']!.default
    const app = (definition.inlineSchema as { parse: (raw: unknown) => object }).parse({
      type: 'example',
      entity: 'switch.kettle',
    })
    const mocked = (definition.mock as (app: object) => { entity_id: string }[])(app)
    useEntitiesStore().entities = Object.fromEntries(mocked.map((e) => [e.entity_id, e])) as never
    const widget = (definition.widget as { widgetScreen: unknown }).widgetScreen
    for (const [part, props] of [
      [widget, { app, size: '2x1', mode: 'dashboard' }],
      [definition.screen, { app }],
    ] as const) {
      const wrapper = mount(await load(part), { props })
      await flushPromises()
      expect(wrapper.text()).toContain('On')
      wrapper.unmount()
    }
  })

  it('face: renders with its default options', async () => {
    const definition = templates['../../templates/face/index.ts']!.default
    const wrapper = mount(await load(definition.screen), {
      props: { options: { color: '#ff9f0a' }, night: false },
    })
    expect(wrapper.find('time').text()).toMatch(/\d\d:\d\d/)
  })

  it('theme: sets every token, and ships its lite version', () => {
    const scss = import.meta.glob<string>(
      ['../../templates/theme/*.scss', '../themes/glass/tokens.scss'],
      { eager: true, query: '?raw', import: 'default' },
    )
    const tokens = (file: string) => [...scss[file]!.matchAll(/(--[a-z-]+):/g)].map((m) => m[1])
    expect(tokens('../../templates/theme/tokens.scss')).toEqual(
      tokens('../themes/glass/tokens.scss'),
    )
    expect(templates['../../templates/theme/index.ts']!.default.graphics).toContain('lite')
    expect('../../templates/theme/lite.scss' in scss).toBe(true)
  })
})
